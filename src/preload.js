const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  getModels: (provider) => ipcRenderer.invoke('get-models', provider),
  sendMessage: (payload) => ipcRenderer.invoke('send-message', payload),
  downloadModel: (model) => ipcRenderer.invoke('download-model', model),
  onStreamUpdate: (callback) => ipcRenderer.on('stream-update', (_event, data) => callback(data)),
  abortRequest: (requestId) => ipcRenderer.send('abort-request', requestId),
  deleteModel: (model) => ipcRenderer.invoke('delete-model', model),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  saveSettings: (patch) => ipcRenderer.invoke('save-settings', patch),
  getBackendStatus: () => ipcRenderer.invoke('get-backend-status'),
  onBackendStatus: (callback) => ipcRenderer.on('backend-status', (_event, data) => callback(data)),
  restartOllama: () => ipcRenderer.invoke('restart-ollama'),
  restartOpenCode: () => ipcRenderer.invoke('restart-opencode'),
  getIntegrationStatus: () => ipcRenderer.invoke('get-integration-status'),
  getAgentInfo: () => ipcRenderer.invoke('get-agent-info'),
  pickProject: () => ipcRenderer.invoke('pick-project'),
  listProject: (root, path) => ipcRenderer.invoke('list-project', { root, path }),
  inspectProject: (root) => ipcRenderer.invoke('inspect-project', root),
  createWorktree: (root, base) => ipcRenderer.invoke('create-worktree', root, base),
  listChanges: (root, base) => ipcRenderer.invoke('list-changes', root, base),
  readDiff: (root, base, file, untracked) => ipcRenderer.invoke('read-diff', root, base, file, untracked),
  revealProject: (root) => ipcRenderer.invoke('reveal-project', root),
  cliAvailable: (provider) => ipcRenderer.invoke('cli-available', provider),
});
